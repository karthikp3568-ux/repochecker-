import { open, readdir, readFile, stat } from "node:fs/promises";
import path from "node:path";
import ignore, { type Ignore } from "ignore";

/** Directories that are never source (spec §5.1). Collapsed in the tree, skipped by tools. */
export const EXCLUDED_DIRS = new Set([
  "node_modules",
  "vendor",
  "dist",
  "build",
  ".next",
  "out",
  "target",
  "venv",
  ".venv",
  "env",
  "__pycache__",
  ".git",
  ".idea",
  ".vscode",
  "coverage",
  ".gradle",
  ".pytest_cache",
  ".mypy_cache",
  ".tox",
  "bower_components",
  ".nuxt",
  ".svelte-kit",
  ".turbo",
  ".cache",
  "Pods",
  "DerivedData",
]);

const LOCKFILES = new Set([
  "package-lock.json",
  "yarn.lock",
  "pnpm-lock.yaml",
  "bun.lockb",
  "poetry.lock",
  "Pipfile.lock",
  "Cargo.lock",
  "composer.lock",
  "Gemfile.lock",
  "go.sum",
  "mix.lock",
  "packages.lock.json",
]);

const BINARY_EXT =
  /\.(png|jpe?g|gif|bmp|ico|webp|avif|tiff?|psd|svgz|mp[34]|m4a|wav|ogg|flac|mov|avi|mkv|webm|pdf|docx?|xlsx?|pptx?|zip|gz|tgz|bz2|xz|7z|rar|jar|war|class|exe|dll|so|dylib|a|o|obj|bin|dat|db|sqlite3?|wasm|ttf|otf|woff2?|eot|pyc|pyo|onnx|pt|pth|h5|pkl|npy|npz|parquet|keras|tflite)$/i;

export type FileKind = "source" | "excluded_vendored" | "excluded_generated" | "binary" | "lockfile";

export type WalkedFile = {
  /** POSIX-style path relative to the repo root. */
  path: string;
  size: number;
  kind: FileKind;
  lines: number;
};

export type WalkResult = {
  files: WalkedFile[];
  excludedDirs: string[];
  totalBytes: number;
};

async function loadGitignore(root: string): Promise<Ignore> {
  const ig = ignore();
  try {
    ig.add(await readFile(path.join(root, ".gitignore"), "utf8"));
  } catch {
    // none
  }
  return ig;
}

async function isBinary(abs: string): Promise<boolean> {
  const fh = await open(abs, "r");
  try {
    const buf = Buffer.alloc(8000);
    const { bytesRead } = await fh.read(buf, 0, 8000, 0);
    return buf.subarray(0, bytesRead).includes(0);
  } finally {
    await fh.close();
  }
}

export function isGeneratedHeader(head: string): boolean {
  const first = head.split(/\r?\n/).slice(0, 5).join("\n");
  return /(@generated|\bauto-?generated\b|\bgenerated by\b|DO NOT EDIT|Code generated .* DO NOT EDIT)/i.test(
    first,
  );
}

export function isExcludedPath(rel: string): boolean {
  return rel.split("/").some((seg) => EXCLUDED_DIRS.has(seg));
}

/**
 * Walk a snapshot. Never follows symlinks. Classifies every file so indexing,
 * coverage and tools agree on what counts as "source".
 */
export async function walkRepo(
  root: string,
  limits: { maxFiles: number; maxBytes: number },
): Promise<WalkResult> {
  const ig = await loadGitignore(root);
  const files: WalkedFile[] = [];
  const excludedDirs: string[] = [];
  let totalBytes = 0;
  let seen = 0;

  async function visit(dirRel: string) {
    const entries = await readdir(path.join(root, dirRel), { withFileTypes: true });
    entries.sort((a, b) => a.name.localeCompare(b.name));
    for (const e of entries) {
      const rel = dirRel ? `${dirRel}/${e.name}` : e.name;
      if (e.isSymbolicLink()) continue;
      if (e.isDirectory()) {
        if (e.name === ".git") continue;
        if (EXCLUDED_DIRS.has(e.name) || ig.ignores(`${rel}/`)) {
          excludedDirs.push(rel);
          continue;
        }
        await visit(rel);
        continue;
      }
      if (!e.isFile()) continue;
      seen++;
      if (seen > limits.maxFiles) throw new RepoLimitError(`more than ${limits.maxFiles} files`);
      const abs = path.join(root, rel);
      const { size } = await stat(abs);
      totalBytes += size;
      if (totalBytes > limits.maxBytes)
        throw new RepoLimitError(`more than ${Math.round(limits.maxBytes / 1e6)} MB`);
      if (ig.ignores(rel)) continue;

      let kind: FileKind = "source";
      let lines = 0;
      if (LOCKFILES.has(e.name)) kind = "lockfile";
      else if (/\.min\.(js|css|mjs)$/i.test(e.name) || /\.(map)$/i.test(e.name)) kind = "excluded_generated";
      else if (BINARY_EXT.test(e.name) || size > 2_000_000 || (await isBinary(abs))) kind = "binary";
      else {
        const text = await readFile(abs, "utf8");
        lines = text.length === 0 ? 0 : text.split(/\r?\n/).length - (text.endsWith("\n") ? 1 : 0);
        if (isGeneratedHeader(text.slice(0, 2000))) kind = "excluded_generated";
      }
      files.push({ path: rel, size, kind, lines });
    }
  }

  await visit("");
  return { files, excludedDirs, totalBytes };
}

export class RepoLimitError extends Error {
  constructor(what: string) {
    super(`Repository exceeds limits: ${what}`);
    this.name = "RepoLimitError";
  }
}
